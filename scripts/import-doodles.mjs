// Turns the hand-drawn doodle sheet (one filled <path> per doodle, absolute M/C/L/H/Z commands)
// into components/ui/doodle-paths.ts: each doodle centred and scaled to fill the same 100×100 box.
//
//   node scripts/import-doodles.mjs <sheet.svg> <bboxes.json>
//
// bboxes.json is [{ i, x, y, w, h }] per path in document order, measured with getBBox() in a browser.
import { readFileSync, writeFileSync } from 'node:fs';

// Grid order of the sheet (rows top to bottom, columns left to right) → doodle names.
const NAMES = [
  ['clover', 'pinwheel', 'fern', 'pine'],
  ['star', 'heart', 'blossom', 'cloud'],
  ['acorn', 'sprout', 'daisy', 'grass'],
  ['twig', 'oak', 'bud', 'lavender'],
  ['spiral', 'fan', 'drops', 'log'],
];
const FILL = 84; // the larger side of every doodle, in box units
const SKIP = new Set(['lavender', 'drops', 'log', 'acorn', 'sprout', 'cloud', 'twig', 'oak', 'bud', 'fan']); // on the sheet but not used

const [sheet, boxesFile] = process.argv.slice(2);
const svg = readFileSync(sheet, 'utf8');
const boxes = JSON.parse(readFileSync(boxesFile, 'utf8'));
const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);

const band = (values, count) => {
  const sorted = [...new Set(values)].sort((a, b) => a - b);
  // Split the sorted centres at the (count - 1) largest gaps.
  const gaps = sorted.slice(1).map((v, i) => ({ at: (v + sorted[i]) / 2, size: v - sorted[i] }));
  const cuts = gaps.sort((a, b) => b.size - a.size).slice(0, count - 1).map((g) => g.at).sort((a, b) => a - b);
  return (v) => cuts.filter((c) => v > c).length;
};
const cx = boxes.map((b) => b.x + b.w / 2);
const cy = boxes.map((b) => b.y + b.h / 2);
const col = band(cx, 4);
const row = band(cy, 5);

const r = (v) => Math.round(v * 100) / 100;
function transform(d, box) {
  const s = FILL / Math.max(box.w, box.h);
  const ox = box.x + box.w / 2;
  const oy = box.y + box.h / 2;
  const X = (v) => r((v - ox) * s + 50);
  const Y = (v) => r((v - oy) * s + 50);
  return d.replace(/([MCLHZ])([^MCLHZ]*)/g, (_, cmd, args) => {
    const nums = (args.match(/-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/gi) ?? []).map(Number);
    if (cmd === 'Z') return 'Z';
    if (cmd === 'H') return `H${nums.map(X).join(' ')}`;
    return cmd + nums.map((v, i) => (i % 2 ? Y(v) : X(v))).join(' ');
  });
}

const entries = boxes.map((box, i) => ({ name: NAMES[row(cy[i])][col(cx[i])], d: transform(ds[i], box) }));
const order = NAMES.flat();
entries.sort((a, b) => order.indexOf(a.name) - order.indexOf(b.name));
if (new Set(entries.map((e) => e.name)).size !== order.length) throw new Error('grid mapping is not one-to-one');

const body = entries.filter((e) => !SKIP.has(e.name)).map((e) => `  ${e.name}: '${e.d}',`).join('\n');
writeFileSync(
  'components/ui/doodle-paths.ts',
  `// Generated by scripts/import-doodles.mjs from the hand-drawn doodle sheet; do not edit by hand.
// Each doodle is a filled outline in a 100×100 box, its larger side ${FILL} units, centred.
export const DOODLE_PATHS = {
${body}
} as const;
`,
);
